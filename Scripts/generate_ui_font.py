"""Rebuild the dashboard's small 20px Chinese glyph subset (Pillow).

Keep previously generated glyphs and add characters used by qr_ui.c.
The font path is explicit so no external SPI-flash font is required at runtime.
"""
import argparse
import ast
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--font", default="C:/Windows/Fonts/simhei.ttf")
args = parser.parse_args()
source = (root / "User/app/qr_ui.c").read_text(encoding="utf-8")
literals = re.findall(r'"(?:[^"\\]|\\.)*"', source)
labels = [ast.literal_eval(s).encode("latin1").decode("utf-8") for s in literals]
existing = root / "User/fonts/ui_glyphs.h"
retained = {chr(int(code, 16)) for code in re.findall(r"^\s*\{0x([0-9a-fA-F]{4}),", existing.read_text(encoding="ascii"), re.M)} if existing.exists() else set()
chars = sorted(retained | {c for s in labels for c in s if ord(c) >= 128}, key=ord)
font = ImageFont.truetype(args.font, 20)
lines = ["/* Generated by Scripts/generate_ui_font.py; 20x20, MSB first. */",
         "#ifndef UI_GLYPHS_H", "#define UI_GLYPHS_H", "#include <stdint.h>",
         f"#define UI_GLYPH_COUNT {len(chars)}u",
         "static const struct { uint16_t code; uint8_t bits[60]; } ui_glyphs[] = {"]
for c in chars:
    image = Image.new("1", (20, 20))
    ImageDraw.Draw(image).text((0, 0), c, font=font, fill=1, anchor="lt")
    data = []
    for y in range(20):
        for b in range(3):
            data.append(sum((0x80 >> j) for j in range(8)
                            if b * 8 + j < 20 and image.getpixel((b * 8 + j, y))))
    lines.append(f"    {{0x{ord(c):04X}, {{" + ",".join(f"0x{v:02X}" for v in data) + "}},")
lines += ["};", "#endif", ""]
(root / "User/fonts/ui_glyphs.h").write_text("\n".join(lines), encoding="ascii")
print(f"Generated {len(chars)} glyphs ({len(chars) * 62} bytes)")
